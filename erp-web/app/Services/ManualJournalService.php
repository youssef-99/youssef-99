<?php

namespace App\Services;

use App\Exceptions\ErpException;
use App\Models\JournalEntry;

/**
 * Posting for manual journal vouchers (سندات القيد) entered by users.
 */
class ManualJournalService
{
    public static function recalculate(JournalEntry $entry): JournalEntry
    {
        return $entry->recalculate();
    }

    public static function post(JournalEntry $entry): JournalEntry
    {
        if ($entry->is_posted) {
            throw new ErpException(__('This document is already posted.'));
        }

        $entry->recalculate();
        JournalService::assertBalanced($entry->lines->map(fn ($l) => $l->only(['account_id', 'debit', 'credit']))->all());
        $entry->forceFill(['is_posted' => true, 'posted_at' => now()])->saveQuietly();

        return $entry;
    }

    public static function unpost(JournalEntry $entry): JournalEntry
    {
        if ($entry->source_type) {
            throw new ErpException(__('This entry was generated by a document. Unpost the document instead.'));
        }

        $entry->forceFill(['is_posted' => false, 'posted_at' => null])->saveQuietly();

        return $entry;
    }
}
