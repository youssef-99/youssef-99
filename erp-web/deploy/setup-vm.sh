#!/usr/bin/env bash
# Prepares an Ubuntu 24.04 VM for ERP Web: PHP-FPM, Caddy (automatic HTTPS), a system user, data
# directories, generated secrets and systemd units for the queue worker, scheduler and nightly backups.
# Re-runnable: deploy.sh runs it on every deploy, then activate-release.sh installs the code.
#
#   sudo bash setup-vm.sh <domain>               # e.g. my-erp.uaenorth.cloudapp.azure.com
#   sudo bash setup-vm.sh <domain> --only-env    # only create/update the env and admin password files
#
# Secrets are generated once in /etc/erp-web/erp-web.env and never overwritten (a re-run only updates
# APP_URL when the domain changes). Back this file up: its APP_KEY decrypts the stored ZATCA EGS
# secrets and must never change.
#
# Overridable paths: ERP_APP_DIR, ERP_DATA_DIR, ERP_ETC_DIR, ERP_BACKUP_DIR, ERP_USER, ERP_PHP.
# ERP_RUN_AS_SELF=1 with --only-env skips the root check and chown (tests).
set -euo pipefail

# Bump when the packages or system configuration below change, so the next deploy re-runs apt.
PROVISION_VERSION=1

ERP_APP_DIR="${ERP_APP_DIR:-/opt/erp-web}"
ERP_DATA_DIR="${ERP_DATA_DIR:-/var/lib/erp-web}"
ERP_ETC_DIR="${ERP_ETC_DIR:-/etc/erp-web}"
ERP_BACKUP_DIR="${ERP_BACKUP_DIR:-/var/backups/erp-web}"
ERP_USER="${ERP_USER:-erpweb}"
ERP_PHP="${ERP_PHP:-php8.3}"
ERP_RUN_AS_SELF="${ERP_RUN_AS_SELF:-0}"
PHP_VERSION="${ERP_PHP_VERSION:-${ERP_PHP#php}}"

ENV_FILE="$ERP_ETC_DIR/erp-web.env"
ADMIN_PASSWORD_FILE="$ERP_ETC_DIR/initial-admin-password"
DB_FILE="$ERP_DATA_DIR/database/database.sqlite"
PROVISION_STAMP="$ERP_DATA_DIR/.provision-version"
FPM_SOCKET=/run/php/erp-web-fpm.sock
FPM_SERVICE="php$PHP_VERSION-fpm"
FPM_DIR="/etc/php/$PHP_VERSION/fpm"
CADDY_SITES_DIR=/etc/caddy/sites
MANAGED_MARK="Managed by erp-web deploy/setup-vm.sh"

usage() {
  echo "usage: setup-vm.sh <domain> [--only-env]" >&2
  exit 2
}

die() {
  printf 'setup-vm: %s\n' "$*" >&2
  exit 1
}

DOMAIN=""
ONLY_ENV=0
for arg in "$@"; do
  case "$arg" in
    --only-env) ONLY_ENV=1 ;;
    -*) usage ;;
    *) [ -z "$DOMAIN" ] || usage; DOMAIN="$arg" ;;
  esac
done
[ -n "$DOMAIN" ] || usage
DOMAIN="$(printf '%s' "$DOMAIN" | tr '[:upper:]' '[:lower:]')"
# A plain DNS name: it is written into the env file and the Caddyfile.
[[ "$DOMAIN" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]] || die "invalid domain: $DOMAIN"

if [ "$(id -u)" -ne 0 ] && ! { [ "$ONLY_ENV" = 1 ] && [ "$ERP_RUN_AS_SELF" = 1 ]; }; then
  die "run as root (sudo bash setup-vm.sh $DOMAIN)"
fi

# set_owner <owner:group> <path>... ; skipped in tests.
set_owner() {
  [ "$ERP_RUN_AS_SELF" = 1 ] && return 0
  chown "$@"
}

# write_file <path> <mode>: replaces <path> with stdin when the content differs. Returns 1 when unchanged.
# Callers test the result, which turns off "set -e" inside, hence the explicit checks.
write_file() {
  local path="$1" mode="$2" tmp
  tmp="$(mktemp "$path.XXXXXX")" || die "cannot write $path"
  cat >"$tmp" || die "cannot write $path"
  if [ -f "$path" ] && cmp -s "$tmp" "$path"; then
    rm -f "$tmp"
    return 1
  fi
  chmod "$mode" "$tmp" || die "cannot write $path"
  mv -f "$tmp" "$path" || die "cannot write $path"
}

random_base64() {
  head -c "$1" /dev/urandom | base64 | tr -d '\n'
}

# --- Secrets: generated once, never overwritten ------------------------------------------------

write_env_files() {
  local tmp current_url
  mkdir -p "$ERP_ETC_DIR"
  chmod 0750 "$ERP_ETC_DIR"
  set_owner "root:$ERP_USER" "$ERP_ETC_DIR"

  if [ ! -f "$ENV_FILE" ]; then
    tmp="$(mktemp "$ENV_FILE.XXXXXX")"
    cat >"$tmp" <<EOF
# ERP Web production settings, generated by deploy/setup-vm.sh on $(date -u +%Y-%m-%d).
# BACK UP THIS FILE. APP_KEY decrypts the ZATCA EGS secrets stored in the database: never change it.
# setup-vm.sh only ever updates APP_URL here. The config is cached, so after editing run:
#   sudo bash $ERP_APP_DIR/current/deploy/activate-release.sh --refresh
APP_NAME="ERP Web"
APP_ENV=production
APP_DEBUG=false
APP_KEY=base64:$(random_base64 32)
APP_URL=https://$DOMAIN
APP_LOCALE=ar
APP_FALLBACK_LOCALE=en

LOG_CHANNEL=stack
LOG_STACK=daily
LOG_LEVEL=warning

DB_CONNECTION=sqlite
DB_DATABASE=$DB_FILE

SESSION_DRIVER=database
SESSION_SECURE_COOKIE=true
CACHE_STORE=database
QUEUE_CONNECTION=database
FILESYSTEM_DISK=local
MAIL_MAILER=log

ZATCA_ENABLED=true
ZATCA_ENVIRONMENT=sandbox
ZATCA_SUBMISSION_MODE=on_post
ZATCA_OFFLINE=false
RASD_MODE=sandbox
ERP_SINGLE_SESSION=true
EOF
    chmod 0640 "$tmp"
    set_owner "root:$ERP_USER" "$tmp"
    mv -f "$tmp" "$ENV_FILE"
    echo "Created $ENV_FILE (back it up: its APP_KEY decrypts the ZATCA EGS secrets)"
  else
    current_url="$(sed -n 's/^APP_URL=//p' "$ENV_FILE" | tail -n 1 | tr -d "\"'")"
    if [ "$current_url" != "https://$DOMAIN" ]; then
      tmp="$(mktemp "$ENV_FILE.XXXXXX")"
      if grep -q '^APP_URL=' "$ENV_FILE"; then
        sed "s|^APP_URL=.*|APP_URL=https://$DOMAIN|" "$ENV_FILE" >"$tmp"
      else
        { cat "$ENV_FILE"; echo "APP_URL=https://$DOMAIN"; } >"$tmp"
      fi
      chmod 0640 "$tmp"
      set_owner "root:$ERP_USER" "$tmp"
      mv -f "$tmp" "$ENV_FILE"
      echo "Updated APP_URL in $ENV_FILE to https://$DOMAIN"
    fi
  fi
  chmod 0640 "$ENV_FILE"
  set_owner "root:$ERP_USER" "$ENV_FILE"

  # Used once by activate-release.sh to create the "admin" user. Never printed.
  if [ ! -f "$ADMIN_PASSWORD_FILE" ]; then
    tmp="$(mktemp "$ADMIN_PASSWORD_FILE.XXXXXX")"
    random_base64 18 | tr '+/' '-_' >"$tmp"
    echo >>"$tmp"
    chmod 0600 "$tmp"
    set_owner root:root "$tmp"
    mv -f "$tmp" "$ADMIN_PASSWORD_FILE"
  fi
  chmod 0600 "$ADMIN_PASSWORD_FILE"
  set_owner root:root "$ADMIN_PASSWORD_FILE"
}

if [ "$ONLY_ENV" = 1 ]; then
  if [ "$ERP_RUN_AS_SELF" != 1 ] && ! id -u "$ERP_USER" >/dev/null 2>&1; then
    useradd --system --user-group --home-dir "$ERP_DATA_DIR" --no-create-home --shell /usr/sbin/nologin "$ERP_USER"
  fi
  write_env_files
  exit 0
fi

# --- Packages ----------------------------------------------------------------------------------

export DEBIAN_FRONTEND=noninteractive
if [ "$(cat "$PROVISION_STAMP" 2>/dev/null || true)" != "$PROVISION_VERSION" ]; then
  echo "Installing packages (PHP $PHP_VERSION, Caddy, SQLite)"
  # On a fresh VM, cloud-init and unattended-upgrades may still hold the dpkg lock: wait for them.
  if command -v cloud-init >/dev/null 2>&1; then
    cloud-init status --wait >/dev/null 2>&1 || true
  fi
  apt-get update -q -o Acquire::Retries=3 -o DPkg::Lock::Timeout=600 >/dev/null
  # Ubuntu 24.04's own PHP 8.3. intl is needed for amounts in words.
  apt-get install -y -q --no-install-recommends -o DPkg::Lock::Timeout=600 \
    -o Dpkg::Options::=--force-confdef -o Dpkg::Options::=--force-confold \
    "php$PHP_VERSION-cli" "php$PHP_VERSION-fpm" "php$PHP_VERSION-sqlite3" "php$PHP_VERSION-mbstring" \
    "php$PHP_VERSION-xml" "php$PHP_VERSION-curl" "php$PHP_VERSION-zip" "php$PHP_VERSION-intl" \
    "php$PHP_VERSION-bcmath" "php$PHP_VERSION-gd" "php$PHP_VERSION-opcache" \
    caddy sqlite3 unzip curl ca-certificates unattended-upgrades >/dev/null
  PROVISIONED_NOW=1
else
  PROVISIONED_NOW=0
fi
PHP_BIN="$(command -v "$ERP_PHP")" || die "$ERP_PHP is not installed"

# Security updates install themselves (Ubuntu's unattended-upgrades, security pocket only).
write_file /etc/apt/apt.conf.d/20auto-upgrades 0644 <<'EOF' || true
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
EOF

# 1 GB RAM VMs need swap for traffic spikes.
if [ -z "$(swapon --noheadings --show=NAME 2>/dev/null)" ]; then
  if [ ! -f /swapfile ]; then
    fallocate -l 1G /swapfile || dd if=/dev/zero of=/swapfile bs=1M count=1024 status=none
    chmod 600 /swapfile
    mkswap /swapfile >/dev/null
  fi
  swapon /swapfile
  grep -q '^/swapfile ' /etc/fstab || echo '/swapfile none swap sw 0 0' >>/etc/fstab
fi

# --- User and directories ----------------------------------------------------------------------

id -u "$ERP_USER" >/dev/null 2>&1 \
  || useradd --system --user-group --home-dir "$ERP_DATA_DIR" --no-create-home --shell /usr/sbin/nologin "$ERP_USER"

install -d -o root -g root -m 0755 "$ERP_APP_DIR" "$ERP_APP_DIR/releases"
# Caddy (another user) serves storage/app/public through public/storage: it may traverse, not list.
install -d -o "$ERP_USER" -g "$ERP_USER" -m 0751 "$ERP_DATA_DIR" "$ERP_DATA_DIR/storage" "$ERP_DATA_DIR/storage/app"
install -d -o "$ERP_USER" -g "$ERP_USER" -m 0755 "$ERP_DATA_DIR/storage/app/public"
install -d -o "$ERP_USER" -g "$ERP_USER" -m 0750 \
  "$ERP_DATA_DIR/storage/app/private" "$ERP_DATA_DIR/storage/framework" \
  "$ERP_DATA_DIR/storage/framework/cache" "$ERP_DATA_DIR/storage/framework/cache/data" \
  "$ERP_DATA_DIR/storage/framework/sessions" "$ERP_DATA_DIR/storage/framework/views" \
  "$ERP_DATA_DIR/storage/logs" "$ERP_DATA_DIR/database"
# Repairs files created by a root-run artisan command, which would otherwise break logging.
chown -R "$ERP_USER:$ERP_USER" "$ERP_DATA_DIR/storage" "$ERP_DATA_DIR/database"
install -d -o root -g root -m 0700 "$ERP_BACKUP_DIR"

write_env_files

# --- PHP-FPM -----------------------------------------------------------------------------------

fpm_changed=0
write_file "$FPM_DIR/pool.d/erp-web.conf" 0644 <<EOF && fpm_changed=1
; $MANAGED_MARK (overwritten on every deploy).
[erp-web]
user = $ERP_USER
group = $ERP_USER
listen = $FPM_SOCKET
listen.owner = caddy
listen.group = caddy
listen.mode = 0660

; Sized for a 1 GB VM: no idle workers, at most 5 (typically 40-80 MB each).
pm = ondemand
pm.max_children = 5
pm.process_idle_timeout = 20s
pm.max_requests = 500
request_terminate_timeout = 120s
security.limit_extensions = .php
catch_workers_output = yes
decorate_workers_output = no

php_admin_value[memory_limit] = 256M
php_admin_value[upload_max_filesize] = 25M
php_admin_value[post_max_size] = 25M
php_admin_value[max_execution_time] = 120
php_admin_flag[expose_php] = off
php_admin_flag[display_errors] = off
php_admin_flag[log_errors] = on
; Every release reloads PHP-FPM, so opcache never needs to check file timestamps.
php_admin_flag[opcache.enable] = on
php_admin_flag[opcache.validate_timestamps] = off
EOF
# Shared-memory sizes can only be set for the whole FPM master, not per pool.
write_file "$FPM_DIR/conf.d/99-erp-web.ini" 0644 <<EOF && fpm_changed=1
; $MANAGED_MARK
opcache.memory_consumption = 128
opcache.interned_strings_buffer = 16
opcache.max_accelerated_files = 20000
EOF
if [ -f "$FPM_DIR/pool.d/www.conf" ]; then
  mv -f "$FPM_DIR/pool.d/www.conf" "$FPM_DIR/pool.d/www.conf.disabled"
  fpm_changed=1
fi
"php-fpm$PHP_VERSION" -t >/dev/null 2>&1 || { "php-fpm$PHP_VERSION" -t; die "invalid PHP-FPM configuration"; }
systemctl enable --quiet "$FPM_SERVICE"
if [ "$fpm_changed" = 1 ] || [ "$PROVISIONED_NOW" = 1 ]; then
  systemctl restart "$FPM_SERVICE"
else
  systemctl start "$FPM_SERVICE"
fi

# --- Caddy -------------------------------------------------------------------------------------

install -d -m 0755 "$CADDY_SITES_DIR"
write_file "$CADDY_SITES_DIR/erp-web.caddy" 0644 <<EOF || true
# $MANAGED_MARK (overwritten on every deploy).
# Caddy obtains and renews the HTTPS certificate for $DOMAIN automatically.
$DOMAIN {
	root * $ERP_APP_DIR/current/public
	encode zstd gzip

	request_body {
		max_size 25MB
	}

	header {
		Strict-Transport-Security "max-age=31536000"
		X-Content-Type-Options nosniff
		Referrer-Policy strict-origin-when-cross-origin
		X-Frame-Options SAMEORIGIN
		-Server
	}

	@dotfiles {
		path */.*
		not path /.well-known/*
	}
	respond @dotfiles 404

	php_fastcgi unix/$FPM_SOCKET
	file_server
}
EOF

# Replace the stock Caddyfile; keep any other Caddyfile and only make sure it imports our site.
stock_md5="$(dpkg-query -W -f='${Conffiles}\n' caddy 2>/dev/null | awk '$1 == "/etc/caddy/Caddyfile" { print $2 }')"
current_md5="$(md5sum /etc/caddy/Caddyfile 2>/dev/null | awk '{ print $1 }' || true)"
if [ ! -f /etc/caddy/Caddyfile ] || [ "$current_md5" = "$stock_md5" ] || grep -q "$MANAGED_MARK" /etc/caddy/Caddyfile; then
  write_file /etc/caddy/Caddyfile 0644 <<EOF || true
# $MANAGED_MARK. Add more sites as files in $CADDY_SITES_DIR/.
import $CADDY_SITES_DIR/*.caddy
EOF
elif ! grep -Eq "^[[:space:]]*import[[:space:]]+$CADDY_SITES_DIR/\*\.caddy" /etc/caddy/Caddyfile; then
  printf '\n# Added by erp-web deploy/setup-vm.sh\nimport %s/*.caddy\n' "$CADDY_SITES_DIR" >>/etc/caddy/Caddyfile
fi
if ! caddy_check="$(caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile 2>&1)"; then
  printf '%s\n' "$caddy_check" >&2
  die "invalid Caddy configuration (is $DOMAIN also defined in /etc/caddy/Caddyfile?)"
fi
systemctl enable --quiet caddy
systemctl reload-or-restart caddy

# --- systemd: queue worker, scheduler, backups -------------------------------------------------

write_file /usr/local/sbin/erp-web-backup 0755 <<EOF || true
#!/usr/bin/env bash
# $MANAGED_MARK. Nightly copy of the SQLite database and uploaded files, kept 14 days.
set -euo pipefail
umask 077
stamp="\$(date -u +%Y%m%d-%H%M%S)"
db_copy="$ERP_BACKUP_DIR/database-\$stamp.sqlite3"
sqlite3 "$DB_FILE" ".backup '\$db_copy'"
[ "\$(sqlite3 "\$db_copy" 'PRAGMA quick_check;')" = ok ] || { echo "backup failed its integrity check" >&2; exit 1; }
gzip -f "\$db_copy"
tar -czf "$ERP_BACKUP_DIR/storage-app-\$stamp.tar.gz" -C "$ERP_DATA_DIR/storage" app
chmod 0600 "\$db_copy.gz" "$ERP_BACKUP_DIR/storage-app-\$stamp.tar.gz"
find "$ERP_BACKUP_DIR" -maxdepth 1 -type f \( -name 'database-*' -o -name 'storage-app-*' \) -mtime +13 -delete
EOF

write_file /etc/systemd/system/erp-web-queue.service 0644 <<EOF || true
# $MANAGED_MARK
[Unit]
Description=ERP Web queue worker
After=network.target
ConditionPathExists=$ERP_APP_DIR/current/artisan

[Service]
User=$ERP_USER
Group=$ERP_USER
WorkingDirectory=$ERP_APP_DIR/current
ExecStart=$PHP_BIN artisan queue:work --sleep=3 --tries=3 --max-time=3600
Restart=always
RestartSec=5
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true

[Install]
WantedBy=multi-user.target
EOF

write_file /etc/systemd/system/erp-web-scheduler.service 0644 <<EOF || true
# $MANAGED_MARK
[Unit]
Description=ERP Web scheduler (php artisan schedule:run)
After=network.target
ConditionPathExists=$ERP_APP_DIR/current/artisan

[Service]
Type=oneshot
User=$ERP_USER
Group=$ERP_USER
WorkingDirectory=$ERP_APP_DIR/current
ExecStart=$PHP_BIN artisan schedule:run --no-interaction
# "No scheduled commands are ready to run" every minute is noise; errors still reach the journal.
StandardOutput=null
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true
EOF

write_file /etc/systemd/system/erp-web-scheduler.timer 0644 <<EOF || true
# $MANAGED_MARK
[Unit]
Description=Run the ERP Web scheduler every minute

[Timer]
OnCalendar=*-*-* *:*:00
AccuracySec=1s

[Install]
WantedBy=timers.target
EOF

write_file /etc/systemd/system/erp-web-backup.service 0644 <<EOF || true
# $MANAGED_MARK
[Unit]
Description=ERP Web nightly backup (SQLite database and storage/app)
ConditionPathExists=$DB_FILE

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/erp-web-backup
Nice=10
IOSchedulingClass=idle
EOF

write_file /etc/systemd/system/erp-web-backup.timer 0644 <<EOF || true
# $MANAGED_MARK
[Unit]
Description=Back up ERP Web every night

[Timer]
# 02:15 in Riyadh (UTC+3).
OnCalendar=*-*-* 23:15:00 UTC
RandomizedDelaySec=10m
Persistent=true

[Install]
WantedBy=timers.target
EOF

systemctl daemon-reload
systemctl enable --quiet erp-web-queue.service
systemctl enable --quiet --now erp-web-scheduler.timer
# The nightly backup covers SQLite only; another database brings its own backups.
db_connection="$(sed -n 's/^DB_CONNECTION=//p' "$ENV_FILE" | tail -n 1 | tr -d "\"'")"
if [ "${db_connection:-sqlite}" = sqlite ]; then
  systemctl enable --quiet --now erp-web-backup.timer
else
  systemctl disable --quiet --now erp-web-backup.timer
fi

echo "$PROVISION_VERSION" >"$PROVISION_STAMP"

echo "VM ready for https://$DOMAIN"
echo "Initial admin password (user: admin): sudo cat $ADMIN_PASSWORD_FILE"
